"""Durable message admission and effect receipts shared by Wake and A2A."""
from __future__ import annotations

from dataclasses import dataclass, field
import hashlib
import json
from decimal import Decimal
import math
import os
from typing import Callable

from .runtime_delivery import RuntimeSubmission


@dataclass(frozen=True)
class Message:
    identifier: str
    source: str
    scope: str
    recipient: str
    expires_at_micros: int
    payload: str = field(repr=False)
    sender: str | None = None
    in_reply_to: str | None = None
    not_before_micros: int | None = None
    busy_policy: str = 'wait'
    order_recipient: str | None = None

    def __post_init__(self):
        if self.busy_policy not in ('wait', 'queue', 'idle-only'):
            raise ValueError('invalid message busy policy')
        if self.source not in ('direct', 'wake'):
            raise ValueError('unsupported message source')
        for value in (self.identifier, self.scope, self.recipient):
            if not isinstance(value, str) or not value or len(value) > 1024:
                raise ValueError('invalid message identity')
        if type(self.expires_at_micros) is not int or not 0 < self.expires_at_micros < 2**63:
            raise ValueError('invalid message expiry')
        if self.not_before_micros is not None and (type(self.not_before_micros) is not int
                                                   or not 0 < self.not_before_micros < 2**63):
            raise ValueError('invalid message eligibility')
        if not isinstance(self.payload, str):
            raise ValueError('invalid message payload')


@dataclass(frozen=True)
class DeliveryReceipt:
    state: str
    receipt_id: str | None = None
    reason: str | None = None
    evidence_kind: str | None = None
    execution: str | None = None
    acknowledgment: str | None = None


_SCHEMA = (
    """CREATE TABLE IF NOT EXISTS wake_messages_v1 (
       scope text NOT NULL, message_id text NOT NULL, source text NOT NULL,
       recipient text NOT NULL, expires_at_micros bigint NOT NULL CHECK (expires_at_micros > 0),
       payload text NOT NULL, sender text, in_reply_to text, not_before_micros bigint,
       PRIMARY KEY (scope, message_id))""",
    'ALTER TABLE wake_messages_v1 ADD COLUMN IF NOT EXISTS not_before_micros bigint',
    """CREATE TABLE IF NOT EXISTS wake_message_attempts_v1 (
       scope text NOT NULL, message_id text NOT NULL, attempt_id text NOT NULL,
       state text NOT NULL CHECK (state IN ('submitting','submitted','unsent','uncertain')),
       receipt_id text, reason text, evidence_kind text, execution text, acknowledgment text,
       PRIMARY KEY (scope, message_id, attempt_id),
       FOREIGN KEY (scope, message_id) REFERENCES wake_messages_v1 (scope, message_id))""",
    "ALTER TABLE wake_messages_v1 ADD COLUMN IF NOT EXISTS busy_policy text NOT NULL DEFAULT 'wait'",
    "ALTER TABLE wake_messages_v1 ADD COLUMN IF NOT EXISTS bounce_reason text",
    """CREATE TABLE IF NOT EXISTS wake_recipient_dnd_v1 (
       recipient text PRIMARY KEY, thread_id text NOT NULL,
       mode text NOT NULL CHECK (mode IN ('hold','bounce')), until_micros bigint)""",
    """CREATE INDEX IF NOT EXISTS wake_recipient_dnd_thread_v1
       ON wake_recipient_dnd_v1 (thread_id)""",
    """CREATE TABLE IF NOT EXISTS wake_message_interventions_v1 (
       scope text NOT NULL, message_id text NOT NULL, recipient text NOT NULL,
       override_dnd boolean NOT NULL, turn_id text, namespace_recipient text NOT NULL,
       interrupt_state text, override_authorized_by text, interrupt_authorized_by text,
       PRIMARY KEY (scope,message_id),
       FOREIGN KEY (scope,message_id) REFERENCES wake_messages_v1 (scope,message_id))""",
    'ALTER TABLE wake_messages_v1 ADD COLUMN IF NOT EXISTS delivery_ordinal bigint GENERATED BY DEFAULT AS IDENTITY',
    'ALTER TABLE wake_messages_v1 ADD COLUMN IF NOT EXISTS order_recipient text',
    'ALTER TABLE wake_messages_v1 ADD COLUMN IF NOT EXISTS local_terminal boolean NOT NULL DEFAULT false',
    'CREATE INDEX IF NOT EXISTS wake_message_recipient_order_v1 ON wake_messages_v1 (order_recipient,delivery_ordinal)',
)


class PostgresMessages:
    """The owner commits before external I/O and cannot replay uncertain effects."""

    def __init__(self, dsn: str, *, cutover_id: str | None = None):
        self._dsn = dsn
        self._cutover_id = cutover_id

    def _connect(self):
        import psycopg

        conn = psycopg.connect(self._dsn, connect_timeout=3,
                               options='-c statement_timeout=3000 -c lock_timeout=2000')
        if self._cutover_id is not None:
            try:
                verified = conn.execute(
                    'SELECT 1 FROM wake_message_cutovers_v1 WHERE cutover_id=%s',
                    (self._cutover_id,)).fetchone()
                if verified is None:
                    raise ValueError('active message cutover is unavailable in the configured database')
            except BaseException:
                conn.close()
                raise
        return conn

    def initialize(self):
        with self._connect() as conn:
            # Concurrent process startup can otherwise race on CREATE IF NOT EXISTS.
            conn.execute('SELECT pg_advisory_xact_lock(%s)', (80499432601277,))
            for statement in _SCHEMA:
                conn.execute(statement)

    @staticmethod
    def _identity(message):
        return message.scope, message.identifier

    def admit(self, message: Message):
        with self._connect() as conn:
            self._admit(conn, message)

    def _admit(self, conn, message):
        identity = self._identity(message)
        values = (message.source, message.recipient, message.expires_at_micros,
                  message.payload, message.sender, message.in_reply_to, message.not_before_micros, message.busy_policy)
        conn.execute(
            """INSERT INTO wake_messages_v1
               (scope,message_id,source,recipient,expires_at_micros,payload,sender,in_reply_to,not_before_micros,busy_policy)
               VALUES (%s,%s,%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT DO NOTHING""",
            (*identity, *values))
        original = conn.execute(
            """SELECT source,recipient,expires_at_micros,payload,sender,in_reply_to,not_before_micros,busy_policy
               FROM wake_messages_v1 WHERE scope=%s AND message_id=%s FOR UPDATE""",
            identity).fetchone()
        if original != values:
            raise ValueError('message identity already binds a different envelope')

        if message.order_recipient is not None:
            updated = conn.execute(
                """UPDATE wake_messages_v1 SET order_recipient=%s WHERE scope=%s AND message_id=%s
                   AND (order_recipient IS NULL OR order_recipient=%s)""",
                (message.order_recipient, *identity, message.order_recipient))
            if updated.rowcount != 1:
                raise ValueError('message recipient binding changed')

    def bound_recipient(self, message):
        with self._connect() as conn:
            return conn.execute(
                'SELECT order_recipient FROM wake_messages_v1 WHERE scope=%s AND message_id=%s',
                self._identity(message)).fetchone()

    def waiting_reason(self, message, lower, upper):
        with self._connect() as conn:
            row = conn.execute(
                'SELECT order_recipient,delivery_ordinal FROM wake_messages_v1 WHERE scope=%s AND message_id=%s',
                self._identity(message)).fetchone()
            return self._waiting_reason(conn, message, lower, upper, *row) if row is not None else None

    def retire_waiting(self, scope, identifier):
        with self._connect() as conn:
            conn.execute(
                'UPDATE wake_messages_v1 SET local_terminal=true WHERE scope=%s AND message_id=%s',
                (scope, identifier))

    def _waiting_reason(self, conn, message, lower, upper, recipient, ordinal):
        if recipient is None or lower is None or upper is None:
            return None
        earlier = conn.execute(
            """SELECT 1 FROM wake_messages_v1 m
               WHERE m.order_recipient=%s AND m.delivery_ordinal<%s
                 AND NOT m.local_terminal AND m.bounce_reason IS NULL
                 AND m.expires_at_micros>%s
                 AND (m.not_before_micros IS NULL OR m.not_before_micros<=%s)
                 AND NOT EXISTS (
                     SELECT 1 FROM wake_message_attempts_v1 a
                     WHERE a.scope=m.scope AND a.message_id=m.message_id AND a.state='submitted')
               LIMIT 1""", (recipient, ordinal, upper, lower)).fetchone()
        if earlier:
            return 'recipient_fifo_wait'
        # An unknown effect can still have reached a stock harness. It must
        # resolve before this recipient accepts another message.
        uncertain = conn.execute(
            """SELECT 1 FROM wake_messages_v1 m JOIN wake_message_attempts_v1 a USING (scope,message_id)
               WHERE m.order_recipient=%s AND (m.scope,m.message_id)<>(%s,%s)
                 AND a.state IN ('submitting','uncertain') LIMIT 1""",
            (recipient, *self._identity(message))).fetchone()
        return 'recipient_effect_unresolved' if uncertain else None

    def set_dnd(self, recipient, thread_id, mode, until_micros=None):
        with self._connect() as conn:
            if mode == 'clear':
                conn.execute('DELETE FROM wake_recipient_dnd_v1 WHERE recipient=%s', (recipient,))
            elif mode in ('hold', 'bounce'):
                conn.execute(
                    """INSERT INTO wake_recipient_dnd_v1 (recipient,thread_id,mode,until_micros)
                       VALUES (%s,%s,%s,%s) ON CONFLICT (recipient)
                       DO UPDATE SET mode=excluded.mode, until_micros=excluded.until_micros""",
                    (recipient, thread_id, mode, until_micros))
            else:
                raise ValueError('invalid DND setting')

    def dnd(self, recipient, now_lower):
        with self._connect() as conn:
            row = conn.execute('SELECT mode,until_micros FROM wake_recipient_dnd_v1 WHERE recipient=%s',
                               (recipient,)).fetchone()
        if row and (row[1] is None or now_lower is None or now_lower < row[1]):
            return row[0]
        return None

    def has_dnd(self, thread_id):
        with self._connect() as conn:
            return conn.execute('SELECT 1 FROM wake_recipient_dnd_v1 WHERE thread_id=%s LIMIT 1',
                                (thread_id,)).fetchone() is not None

    def record_bounce(self, message, reason):
        with self._connect() as conn:
            self._admit(conn, message)
            identity = self._identity(message)
            row = conn.execute(
                """SELECT 1 FROM wake_message_attempts_v1
                   WHERE scope=%s AND message_id=%s AND state <> 'unsent' LIMIT 1""", identity).fetchone()
            if row:
                return False
            conn.execute(
                """UPDATE wake_messages_v1 SET bounce_reason=coalesce(bounce_reason,%s)
                   WHERE scope=%s AND message_id=%s""", (reason, *identity))
            return True

    def intervene(self, message, exact_recipient, *, override, turn_id, actor):
        with self._connect() as conn:
            self._admit(conn, message)
            identity = self._identity(message)
            terminal = conn.execute(
                """SELECT bounce_reason FROM wake_messages_v1
                   WHERE scope=%s AND message_id=%s""", identity).fetchone()
            attempted = conn.execute(
                """SELECT 1 FROM wake_message_attempts_v1
                   WHERE scope=%s AND message_id=%s AND state <> 'unsent' LIMIT 1""", identity).fetchone()
            if terminal[0] or attempted:
                raise ValueError('message_already_terminal_or_uncertain')
            result = conn.execute(
                """INSERT INTO wake_message_interventions_v1
                   (scope,message_id,recipient,override_dnd,turn_id,namespace_recipient,override_authorized_by,interrupt_authorized_by)
                   VALUES (%s,%s,%s,%s,%s,%s,%s,%s) ON CONFLICT (scope,message_id)
                   DO UPDATE SET override_dnd=wake_message_interventions_v1.override_dnd OR excluded.override_dnd,
                    turn_id=coalesce(wake_message_interventions_v1.turn_id,excluded.turn_id),
                    override_authorized_by=coalesce(wake_message_interventions_v1.override_authorized_by,
                                                    excluded.override_authorized_by),
                    interrupt_authorized_by=coalesce(wake_message_interventions_v1.interrupt_authorized_by,
                                                     excluded.interrupt_authorized_by)
                   WHERE wake_message_interventions_v1.recipient=excluded.recipient
                     AND wake_message_interventions_v1.namespace_recipient=excluded.namespace_recipient
                     AND (wake_message_interventions_v1.turn_id IS NULL OR excluded.turn_id IS NULL
                          OR wake_message_interventions_v1.turn_id=excluded.turn_id)""",
                (*identity, message.recipient, override, turn_id, exact_recipient,
                 actor if override else None, actor if turn_id else None))
            if result.rowcount != 1:
                raise ValueError('message_intervention_conflict')

    def intervention(self, message):
        with self._connect() as conn:
            return conn.execute(
                """SELECT override_dnd,turn_id,namespace_recipient,interrupt_state
                   FROM wake_message_interventions_v1
                   WHERE scope=%s AND message_id=%s AND recipient=%s""",
                (*self._identity(message), message.recipient)).fetchone()

    def policy_status(self, scope, identifier):
        with self._connect() as conn:
            row = conn.execute(
                """SELECT m.bounce_reason, i.namespace_recipient, i.turn_id, i.interrupt_state,
                          i.override_authorized_by, i.interrupt_authorized_by
                   FROM wake_messages_v1 m LEFT JOIN wake_message_interventions_v1 i USING (scope,message_id)
                   WHERE m.scope=%s AND m.message_id=%s""", (scope, identifier)).fetchone()
        if row is None:
            return None
        bounce, recipient, turn, state, override_receipt, interrupt_receipt = row
        return dict(bounce_reason=bounce, recipient=recipient, turn_id=turn,
                    interruption=(state or 'requested') if turn else None,
                    override_authorization=override_receipt, interrupt_authorization=interrupt_receipt)

    def begin_interrupt(self, message, turn_id):
        with self._connect() as conn:
            return conn.execute(
                """UPDATE wake_message_interventions_v1 SET interrupt_state='uncertain'
                   WHERE scope=%s AND message_id=%s AND turn_id=%s AND interrupt_state IS NULL""",
                (*self._identity(message), turn_id)).rowcount == 1

    def disable_interrupt(self, message, turn_id):
        with self._connect() as conn:
            conn.execute(
                """UPDATE wake_message_interventions_v1 SET interrupt_state='unavailable'
                   WHERE scope=%s AND message_id=%s AND turn_id=%s
                     AND (interrupt_state IS NULL OR interrupt_state='uncertain')""",
                (*self._identity(message), turn_id))

    def finish_interrupt(self, message, turn_id, state):
        with self._connect() as conn:
            conn.execute(
                """UPDATE wake_message_interventions_v1 SET interrupt_state=%s
                   WHERE scope=%s AND message_id=%s AND turn_id=%s AND interrupt_state IN ('uncertain','requested')""",
                (state, *self._identity(message), turn_id))

    def prepare(self, message: Message, attempt_id: str, *, lower=None, upper=None) -> DeliveryReceipt | None:
        identity = self._identity(message)
        with self._connect() as conn:
            self._admit(conn, message)
            bounced, retired, recipient, ordinal = conn.execute(
                """SELECT bounce_reason,local_terminal,order_recipient,delivery_ordinal
                   FROM wake_messages_v1 WHERE scope=%s AND message_id=%s""", identity).fetchone()
            if bounced or retired:
                return DeliveryReceipt('unsent', reason=bounced or 'message_retired')
            if recipient is not None:
                conn.execute('SELECT pg_advisory_xact_lock(hashtextextended(%s, 0))', (recipient,))
            for saved_attempt, *columns in conn.execute(
                    """SELECT attempt_id,state,receipt_id,reason,evidence_kind,execution,acknowledgment
                       FROM wake_message_attempts_v1 WHERE scope=%s AND message_id=%s""",
                    identity):
                saved = DeliveryReceipt(*columns)
                if saved_attempt == attempt_id and saved.state in ('submitted', 'unsent'):
                    return saved
                if saved.state != 'unsent':
                    return DeliveryReceipt('uncertain', reason='original_message_effect_requires_reconciliation')
            waiting = self._waiting_reason(conn, message, lower, upper, recipient, ordinal)
            if waiting:
                return DeliveryReceipt('unsent', reason=waiting)
            conn.execute(
                """INSERT INTO wake_message_attempts_v1(scope,message_id,attempt_id,state)
                   VALUES (%s,%s,%s,'submitting')""", (*identity, attempt_id))
        return None

    def reconcile_acceptance(self, message: Message, attempt_id: str, receipt: DeliveryReceipt):
        """Record a positive observation for the original attempt without submitting."""
        identity = self._identity(message)
        expected = (receipt.state, receipt.receipt_id, receipt.reason, receipt.evidence_kind,
                    receipt.execution, receipt.acknowledgment)
        if receipt.state != 'submitted' or not receipt.receipt_id:
            raise ValueError('reconciliation requires positive transport evidence')
        with self._connect() as conn:
            self._admit(conn, message)
            conn.execute(
                """UPDATE wake_message_attempts_v1
                   SET state=%s,receipt_id=%s,reason=%s,evidence_kind=%s,execution=%s,acknowledgment=%s
                   WHERE scope=%s AND message_id=%s AND attempt_id=%s
                         AND state IN ('submitting','uncertain')""",
                (*expected, *identity, attempt_id))
            row = conn.execute(
                """SELECT state,receipt_id FROM wake_message_attempts_v1
                   WHERE scope=%s AND message_id=%s AND attempt_id=%s""",
                (*identity, attempt_id)).fetchone()
            if row != expected[:2]:
                raise ValueError('original delivery evidence could not be reconciled')

    def finish(self, message: Message, attempt_id: str, receipt: DeliveryReceipt):
        with self._connect() as conn:
            cursor = conn.execute(
                """UPDATE wake_message_attempts_v1
                   SET state=%s,receipt_id=%s,reason=%s,evidence_kind=%s,execution=%s,acknowledgment=%s
                   WHERE scope=%s AND message_id=%s AND attempt_id=%s AND state='submitting'""",
                (receipt.state, receipt.receipt_id, receipt.reason, receipt.evidence_kind,
                 receipt.execution, receipt.acknowledgment, *self._identity(message), attempt_id))
            if cursor.rowcount != 1:
                raise ValueError('message delivery attempt changed')


def configured_store(root=None) -> PostgresMessages | None:
    if root is not None:
        from .message_cutover import activated_store
        active = activated_store(root)
        if active is not None:
            return active
    dsn = os.environ.get('CODEX_WAKE_MESSAGE_DB_DSN')
    return PostgresMessages(dsn) if dsn else None


def deliver(store: PostgresMessages, message: Message, attempt_id: str,
            effect: Callable[[], DeliveryReceipt], *, clock=None) -> DeliveryReceipt:
    """Persist a single effect intent and retain exact transport evidence."""
    from psycopg import Error
    from .native_clock import snapshot
    from .native_intents import valid_utc
    from .message_policy import stable_micros

    clock = clock or snapshot
    try:
        gate = clock()
        cached = store.prepare(message, attempt_id, lower=stable_micros(gate),
                               upper=stable_micros(gate, upper=True))
    except (Error, OSError):
        return DeliveryReceipt('unsent', reason='message_store_unavailable')
    except ValueError:
        return DeliveryReceipt('uncertain', reason='message_identity_conflict')
    if cached is not None:
        return cached

    try:
        utc = clock().get('utc')
        if not valid_utc(utc):
            result = DeliveryReceipt('unsent', reason='message_delivery_time_unavailable')
        elif math.ceil(utc['upper'] * 1_000_000) >= message.expires_at_micros:
            result = DeliveryReceipt('unsent', reason='message_dispatch_window_closed')
        elif (message.not_before_micros is not None
              and math.floor(utc['lower'] * 1_000_000) < message.not_before_micros):
            result = DeliveryReceipt('unsent', reason='message_eligibility_unverified')
        else:
            result = effect()
            if result.state not in ('submitted', 'unsent', 'uncertain'):
                result = DeliveryReceipt('uncertain', reason='message_effect_outcome_unverified')
    except Exception:
        result = DeliveryReceipt('uncertain', reason='message_effect_outcome_unverified')
    try:
        store.finish(message, attempt_id, result)
    except (Error, OSError, ValueError):
        return DeliveryReceipt('uncertain', reason='message_receipt_commit_unverified')
    return result


def scope_for_wake(root):
    # The legacy record ID is retained across both stores. A digest scopes it
    # to the original local owner without publishing its filesystem path.
    return 'wake:' + hashlib.sha256(str(root.resolve()).encode()).hexdigest()


def wake_message(root, record, expires_at_micros, *, order_recipient=None):
    scope = scope_for_wake(root)
    due = record.get('predicate', {}).get('due_at')
    if due:
        from .network_wakes import precise_deadline
        from datetime import UTC, datetime

        delta = precise_deadline(due) - datetime(1970, 1, 1, tzinfo=UTC)
        not_before = (delta.days * 86400 + delta.seconds) * 1_000_000 + delta.microseconds
    else:
        not_before = None
    return Message(record['id'], 'wake', scope, record['target']['thread_id'],
                   expires_at_micros, record['prompt'], not_before_micros=not_before,
                   busy_policy=record['target'].get('busy_policy', 'wait'), order_recipient=order_recipient)


def direct_message(envelope, payload):
    recipient = envelope['recipient']
    exact = json.dumps([recipient['namespace'], recipient['thread_id']], separators=(',', ':'))
    sender = envelope['sender']
    return Message(envelope['message_id'], 'direct', 'a2a:' + envelope['bus_id'], exact,
                   int(Decimal(str(envelope['expires_at'])) * 1_000_000), payload,
                   json.dumps([sender['namespace'], sender['thread_id']], separators=(',', ':')),
                   envelope.get('in_reply_to'), busy_policy=envelope.get('busy_policy', 'wait'),
                   order_recipient=exact if envelope.get('delivery') == 'notify' else None)


def admission_status(store, message):
    from psycopg import Error
    try:
        store.admit(message)
    except (Error, OSError):
        return 'pending_shared_store'
    except ValueError:
        return 'identity_conflict'
    return 'recorded'


def submit_native_message(store, message, attempt_id, submit, *, clock=None):
    if store is None:
        return submit()
    original = None

    def effect():
        nonlocal original
        original = submit()
        state = 'uncertain'
        if original.state == 'accepted':
            state = 'submitted'
        elif original.state == 'not_sent' and original.pre_io:
            state = 'unsent'
        return DeliveryReceipt(state, original.receipt_id, original.reason, original.evidence_kind)

    receipt = deliver(store, message, attempt_id, effect, clock=clock)
    if original is not None and receipt.state in ('submitted', 'unsent'):
        return original
    if receipt.state == 'submitted':
        return RuntimeSubmission('accepted', receipt_id=receipt.receipt_id,
                                 evidence_kind=receipt.evidence_kind or 'none')
    if receipt.state == 'unsent':
        return RuntimeSubmission('not_sent', reason=receipt.reason, pre_io=True)
    return RuntimeSubmission('uncertain', reason=receipt.reason)
